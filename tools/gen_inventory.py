#!/usr/bin/env python3
"""Generate docs/06-inventory.md from the pinned CDDA reference checkout.

Every list in the output is derived mechanically from the source tree, so the
counts in the document are reproducible: re-run this script and the numbers
either match or the reference moved.

Usage:  python3 tools/gen_inventory.py [--ref PATH] [--out PATH]
"""

import argparse
import pathlib
import re
import sys
from collections import Counter, defaultdict

DEFAULT_REF = pathlib.Path("references/Cataclysm-DDA")
DEFAULT_OUT = pathlib.Path("docs/06-inventory.md")


def read(p):
    try:
        return p.read_text(errors="ignore")
    except Exception:
        return ""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ref", default=str(DEFAULT_REF))
    ap.add_argument("--out", default=str(DEFAULT_OUT))
    args = ap.parse_args()

    ref = pathlib.Path(args.ref)
    if not (ref / "src" / "init.cpp").exists():
        sys.exit(f"not a CDDA checkout: {ref}")

    src = [p for p in list((ref / "src").glob("*.cpp")) + list((ref / "src").glob("*.h"))
           if "third-party" not in str(p)]
    text = {p.name: read(p) for p in src}
    lines = {name: t.splitlines() for name, t in text.items()}

    def find_line(name, pattern):
        for i, l in enumerate(lines.get(name, []), 1):
            if re.search(pattern, l):
                return i
        return None

    out = []
    w = out.append

    # ---------------------------------------------------------------- header
    w("# 06 — Code surface inventory")
    w("")
    w("Generated by `tools/gen_inventory.py` from the pinned reference")
    w("(`0.I-1`, commit `7b2efa5`). Every table below is derived mechanically from the")
    w("source tree, so the counts are reproducible rather than remembered. If a count")
    w("here disagrees with a hand-written number elsewhere, this file wins.")
    w("")
    w("Purpose: the port's completeness checklist. [appendix-file-map.md](appendix-file-map.md)")
    w("answers *which files*, this answers *which surfaces inside them*.")
    w("")

    sections = []

    # ------------------------------------------------- 1. content types
    init = lines.get("init.cpp", [])
    types = []
    for i, l in enumerate(init, 1):
        m = re.match(r'\s*add\(\s*"([A-Za-z_0-9]+)"\s*,\s*(.*)$', l)
        if not m:
            continue
        target = m.group(2).strip().rstrip(");").strip()
        if target.startswith("[") or target.startswith("&["):
            target = "inline lambda"
        else:
            target = target.lstrip("&").strip()
        types.append((m.group(1), target, i))
    sections.append(("Content types", len(types),
                     "Every JSON content type the game will load. If the port cannot load one of "
                     "these, mods using it break.",
                     ["| JSON type | Loader | Registered at |", "|---|---|---|"] +
                     [f"| `{t}` | `{fn.split('::')[-1]}` | `src/init.cpp:{ln}` |" for t, fn, ln in types]))

    # ------------------------------------------------- 2. factories
    facs = []
    for name, t in text.items():
        for i, l in enumerate(lines[name], 1):
            m = re.search(r'generic_factory<\s*([\w:]+)\s*>\s+(\w+)', l)
            if m:
                facs.append((m.group(1), m.group(2), name, i))
    facs.sort(key=lambda r: r[0])
    bytype = defaultdict(list)
    for cls, var, name, ln in facs:
        bytype[cls].append((var, name, ln))
    sections.append(("Prototype registries", len(bytype),
                     f"{len(facs)} `generic_factory` instantiations over {len(bytype)} distinct "
                     "prototype types. Each needs a loader and a two-phase (load, then finalise) "
                     "lifecycle in the port.",
                     ["| Prototype type | Instances | Declared in |", "|---|---|---|"] +
                     [f"| `{cls}` | {len(v)} | " + ", ".join(f"`{n}:{ln}`" for _, n, ln in v[:3]) +
                      (" …" if len(v) > 3 else "") + " |"
                      for cls, v in sorted(bytype.items())]))

    # ------------------------------------------------- 3. serialisation
    ser = []
    for name, t in text.items():
        for i, l in enumerate(lines[name], 1):
            m = re.search(r'void\s+([\w:<>]+)::(serialize|deserialize)\s*\(', l)
            if m:
                ser.append((m.group(1), m.group(2), name, i))
    ser_files = Counter(f for _, _, f, _ in ser)
    sections.append(("Persistence surface", len(ser),
                     f"{sum(1 for x in ser if x[1] == 'serialize')} serialize and "
                     f"{sum(1 for x in ser if x[1] == 'deserialize')} deserialize methods across "
                     f"{len(ser_files)} files. This is the save-graph: the list of everything whose "
                     "state survives a save, and therefore the list of components the port must be "
                     "able to write and read.",
                     ["| File | Methods |", "|---|---|"] +
                     [f"| `src/{f}` | {c} |" for f, c in ser_files.most_common()]))

    # ------------------------------------------------- 4. behaviour hooks
    def distinct_funcs(pattern, limit=None):
        s = set()
        for t in text.values():
            s |= set(re.findall(pattern, t))
        return sorted(s)

    hooks = [
        ("Use actions (item activation)", distinct_funcs(r'iuse::(\w+)')),
        ("Examine actions (terrain and furniture)", distinct_funcs(r'iexamine::(\w+)')),
        ("Monster attacks", distinct_funcs(r'mattack::(\w+)')),
        ("Activity actors", distinct_funcs(r'class (\w+)_activity_actor')),
        ("Field processors", distinct_funcs(r'(field_processor_\w+)')),
    ]
    rows = ["| Hook family | Count |", "|---|---|"]
    detail = []
    for label, items in hooks:
        rows.append(f"| {label} | {len(items)} |")
        detail.append(f"**{label}** ({len(items)}): " +
                      ", ".join(f"`{i}`" for i in items) + "\n")
    sections.append(("Behaviour hooked by name", sum(len(i) for _, i in hooks),
                     "Behaviour reached by a string or table lookup rather than by a direct call. "
                     "Every entry is a case the port must reproduce; a missed one is a silent "
                     "behaviour gap.",
                     rows + [""] + detail))

    # ------------------------------------------------- 5. UI surface
    ctx = defaultdict(set)
    ctx_patterns = [
        r'input_context\s+\w+\s*[({]\s*"([A-Za-z_0-9]+)"',
        r'=\s*input_context\(\s*"([A-Za-z_0-9]+)"',
        r'input_category\s*=\s*"([A-Za-z_0-9]+)"',
        r'\bctxt\s*\(\s*"([A-Za-z_0-9]+)"',
    ]
    for name, t in text.items():
        for pat in ctx_patterns:
            for m in re.finditer(pat, t):
                ctx[m.group(1)].add(name)
    menus = defaultdict(int)
    for name, t in text.items():
        menus[name] = len(re.findall(r'\builist\s+\w+\s*;', t))
    menus = {k: v for k, v in menus.items() if v}
    prompt_kinds = ["string_input_popup", "query_popup", "query_yn", "query_int"]
    prompt_totals = {}
    for kind in prompt_kinds:
        prompt_totals[kind] = sum(len(re.findall(r'\b' + kind + r'\b', t)) for t in text.values())
    prompts = defaultdict(int)
    for name, t in text.items():
        prompts[name] = len(re.findall(r'\b(?:' + "|".join(prompt_kinds) + r')\b', t))
    prompts = {k: v for k, v in prompts.items() if v}
    kb = read(ref / "data/raw/keybindings.json")
    kb_actions = len(re.findall(r'"id"\s*:', kb))
    sections.append(("Interface surface", len(ctx),
                     f"{len(ctx)} input contexts, {sum(menus.values())} menu construction sites in "
                     f"{len(menus)} files, {sum(prompts.values())} prompt sites in {len(prompts)} "
                     f"files ({', '.join(f'{k} {v}' for k, v in prompt_totals.items())}), "
                     f"{kb_actions} rebindable actions defined in data. "
                     "This is the checklist for the visual gate: every context is at least one "
                     "screen that must be driven and compared.",
                     ["| Input context | Referenced in |", "|---|---|"] +
                     [f"| `{c}` | " + ", ".join(f"`{f}`" for f in sorted(ctx[c])[:3]) +
                      (" …" if len(ctx[c]) > 3 else "") + " |" for c in sorted(ctx)] +
                     ["", "| File building menus | Menu sites |", "|---|---|"] +
                     [f"| `src/{f}` | {n} |" for f, n in sorted(menus.items(), key=lambda x: -x[1])]))

    # ------------------------------------------------- 6. events and ids
    events = distinct_funcs(r'event_type::(\w+)')
    dmg = distinct_funcs(r'damage_type_id\(\s*"(\w+)"')
    bp = distinct_funcs(r'bodypart_id\(\s*"(\w+)"')
    sounds = distinct_funcs(r'play_variant_sound\(\s*"(\w+)"')
    sections.append(("Named event and id vocabularies", len(events) + len(dmg) + len(bp) + len(sounds),
                     "Identifiers that appear in code as strings. In the port these become typed "
                     "values, which is exactly where a rename silently breaks behaviour.",
                     ["| Vocabulary | Count |", "|---|---|",
                      f"| Event types referenced | {len(events)} |",
                      f"| Damage types referenced | {len(dmg)} |",
                      f"| Body parts referenced | {len(bp)} |",
                      f"| Sound effect ids in code | {len(sounds)} |",
                      "", "**Event types** (" + str(len(events)) + "): " +
                      ", ".join(f"`{e}`" for e in events),
                      "", "**Damage types** (" + str(len(dmg)) + "): " +
                      ", ".join(f"`{d}`" for d in dmg),
                      "", "**Body parts** (" + str(len(bp)) + "): " +
                      ", ".join(f"`{b}`" for b in bp),
                      "", "**Sound ids** (" + str(len(sounds)) + "): " +
                      ", ".join(f"`{s}`" for s in sounds)]))

    # ------------------------------------------------- 7. scripting
    eoc_files = ["effect_on_condition.cpp", "condition.cpp"]
    eoc = 0
    for f in eoc_files:
        eoc += len(re.findall(r'\{\s*"\w+",\s*&?\w+', text.get(f, "")))
    mapgen_builtins = re.findall(r'\{\s*"(\w+)"\s*,\s*&?mapgen_\w+', text.get("mapgen_functions.cpp", ""))
    sections.append(("Data-driven scripting", eoc,
                     "Content can express behaviour without code: effect-on-condition functions, "
                     "dialogue responses, map generators. Each is a mini-language the port must "
                     "implement, not call.",
                     ["| Surface | Count | Where |", "|---|---|---|",
                      f"| Effect-on-condition / condition functions | {eoc} | `src/effect_on_condition.cpp`, `src/condition.cpp` |",
                      f"| Built-in map generator functions | {len(mapgen_builtins)} | `src/mapgen_functions.cpp` |",
                      f"| Map generator JSON files | {len(list((ref / 'data/json/mapgen').rglob('*.json')))} | `data/json/mapgen` |",
                      "", "**Built-in map generators** (" + str(len(mapgen_builtins)) + "): " +
                      ", ".join(f"`{m}`" for m in mapgen_builtins)]))

    # ------------------------------------------------- 8. data volumes
    def count_files(sub, pat="*.json"):
        return len(list((ref / sub).rglob(pat)))

    def count_lines(sub, pat="*.json"):
        return sum(len(read(p).splitlines()) for p in (ref / sub).rglob(pat))

    data_dirs = ["data/json", "data/mods", "data/json/mapgen", "data/raw", "data/core"]
    rows = ["| Data | JSON files | Lines |", "|---|---|---|"]
    for d in data_dirs:
        rows.append(f"| `{d}` | {count_files(d):,} | {count_lines(d):,} |")
    sections.append(("Data volume to load", count_files("data/json") + count_files("data/mods"),
                     "The content the port must accept on day one. A loader that rejects one of "
                     "these files is a regression against every mod.",
                     rows))

    # ------------------------------------------------- write-out
    w("## Summary")
    w("")
    w("| Surface | Count |")
    w("|---|---|")
    for name, n, _, _ in sections:
        w(f"| {name} | {n} |")
    w("")

    for name, n, blurb, body in sections:
        w(f"## {name}")
        w("")
        w(blurb)
        w("")
        for line in body:
            w(line)
        w("")

    w("---")
    w("")
    w("## What this file does not cover")
    w("")
    w("- Behaviour that is written inline in a switch or an if-chain rather than in a table.")
    w("  There is no registry to enumerate; only reading finds it.")
    w("- Which class is an entity and which is a component: that is")
    w("  [07-entity-component-map.md](07-entity-component-map.md).")
    w("- Whether the port is correct: that is [09-testing-plan.md](09-testing-plan.md).")
    w("")

    out_path = pathlib.Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(out) + "\n")
    print(f"wrote {out_path} ({len(out)} lines)")
    for name, n, _, _ in sections:
        print(f"  {n:>6}  {name}")


if __name__ == "__main__":
    main()
