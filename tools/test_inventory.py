#!/usr/bin/env python3
"""Regenerates docs/13-test-inventory.md from the pinned reference.

The inventory is derived, never hand-maintained: run this after moving the
reference pin, and the table follows. Usage: python3 tools/test_inventory.py
"""

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
TESTS = ROOT / "references/Cataclysm-DDA/tests"
OUT = ROOT / "docs/13-test-inventory.md"

# Where the port has already taken something from a file. Kept here rather than
# in the generated table so the table stays mechanical and this stays reviewable.
PORTED = {
    "calendar_test.cpp": "ported (28 assertions, all of them)",
    "coordinate_test.cpp": "ported (strings, operations, comparison, hash, distances, midpoint, combine/remain)",
    "units_test.cpp": "partly (83 of 202 assertions; the rest need time, JSON or options)",
    "rng_test.cpp": "ported (engine stream and every wrapper, against libc++)",
    "options_test.cpp": "ported (21 tests, table and behaviour)",
    "string_ids_test.cpp": "ported (interning, ordinal caches, version invalidation)",
    "generic_factory_test.cpp": "partly (5 of 9 cases)",
}


def cases(text: str) -> int:
    return len(re.findall(r"^TEST_CASE", text, re.MULTILINE))


def tags(text: str) -> list[str]:
    found = set()
    for match in re.finditer(r'TEST_CASE\([^)]*"(\[[^"]*)"', text):
        found.update(re.findall(r"\[[^\]]+\]", match.group(1)))
    return sorted(found)


def needs_world(text: str) -> bool:
    return bool(
        re.search(r"get_avatar|g->|clear_map\(\)|standard_npc|spawn_test_monster", text)
    )


def main() -> None:
    rows = []
    for path in sorted(TESTS.glob("*.cpp")):
        text = path.read_text(errors="replace")
        count = cases(text)
        if count == 0:
            continue
        rows.append(
            (
                path.name,
                count,
                len(text.splitlines()),
                needs_world(text),
                tags(text),
            )
        )

    total_cases = sum(row[1] for row in rows)
    world = sum(row[1] for row in rows if row[3])
    slow = sum(row[1] for row in rows if "[slow]" in row[4])
    hidden = sum(row[1] for row in rows if "[.]" in row[4])

    lines = [
        "# 13 — The reference's own test suite, file by file",
        "",
        "Generated by `tools/test_inventory.py` from the pinned reference",
        "(`references/Cataclysm-DDA/tests`). Do not edit by hand: rerun the script.",
        "",
        "The per-file triage (re-express as a test, keep as an invariant, reproduce as",
        "a session, or drop with a reason) lives in [parts/test-triage.md](parts/test-triage.md);",
        "this page is the mechanical inventory it is checked against.",
        "",
        "This is the map of what upstream already asserts, so that a ported system",
        "can be checked against the same expectations rather than reinvented. It is",
        "**not** an equivalence oracle — see [14-test-porting.md](14-test-porting.md)",
        "for why, and for the rules that turn a case here into a test in the port.",
        "",
        "## Shape of the suite",
        "",
        f"* **{len(rows)} of 218 files contain test cases** - the rest are helpers - "
        f"giving **{total_cases} cases**, "
        f"{sum(row[2] for row in rows):,} lines of test code.",
        f"* **{world} cases need a running game** (`g->`, an avatar, a map, a "
        f"spawned NPC or monster); the other **{total_cases - world}** exercise "
        "algorithms and data on their own.",
        f"* **{slow} cases carry `[slow]`** and CI runs them in a batch of their "
        "own; **{hidden} carry `[.]`**, which means CI skips them entirely.",
        "* Upstream seeds from the clock (`--rng-seed time`) and generates random",
        "  inputs in 27 files, so a failure is not always reproducible. A ported",
        "  case fixes its seed — that is a strict improvement, not a deviation.",
        "",
        "## How to read the table",
        "",
        "| Column | Meaning |",
        "|---|---|",
        "| Cases | `TEST_CASE` count in the file |",
        "| Lines | size of the file |",
        "| Needs a world | the file reaches for game state, so the case cannot run before that subsystem exists |",
        "| Tags | upstream's own labels, the ones CI filters on |",
        "| Port status | what the port has taken from it so far |",
        "",
        "## Files",
        "",
        "| File | Cases | Lines | Needs a world | Tags | Port status |",
        "|---|---:|---:|:--:|---|---|",
    ]
    for name, count, length, world_dep, tag_list in rows:
        status = PORTED.get(name, "—")
        tags_text = ", ".join(tag_list) if tag_list else ""
        lines.append(
            f"| `{name}` | {count} | {length:,} | {'yes' if world_dep else 'no'} "
            f"| {tags_text} | {status} |"
        )

    standalone = [(n, c) for n, c, _, w, _ in rows if not w]
    lines += [
        "",
        "## What is portable now",
        "",
        f"These {len(standalone)} files ({sum(c for _, c in standalone)} cases) run "
        "without a game world, so they can be taken whenever their subject lands:",
        "",
    ]
    for name, count in standalone:
        lines.append(f"* `{name}` — {count} cases")

    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT} with {len(rows)} files and {total_cases} cases")


if __name__ == "__main__":
    main()
