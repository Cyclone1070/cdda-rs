/// `is_cjk_or_emoji`, `src/unicode.cpp:67-73`.
///
/// A binary search over `CJK_OR_EMOJI` for the block containing `ch`. Note that
/// the reference's `lower_bound` comparator only inspects `range.second`, so a
/// character may be reported as CJK by the block *after* the one it is in when
/// that block ends before it and begins after it; the explicit `ch >= it->first`
/// guard keeps the result correct for the sorted, gap-free table.
#[must_use]
pub fn is_cjk_or_emoji(ch: u32) -> bool {
    let mut lo = 0_usize;
    let mut hi = CJK_OR_EMOJI.len();
    while lo < hi {
        let mid = lo + (hi - lo) / 2;
        let Some(&(_, last)) = CJK_OR_EMOJI.get(mid) else {
            return false;
        };
        if last < ch {
            lo = mid + 1;
        } else {
            hi = mid;
        }
    }
    match CJK_OR_EMOJI.get(lo) {
        Some(&(first, _)) => ch >= first,
        None => false,
    }
}

/// The byte range `[from, to)` of `s`, clamped so both ends sit on character
/// boundaries.
fn byte_range(s: &str, from: usize, to: usize) -> &str {
    let start = byte_prefix(s, from).len();
    let end = byte_prefix(s, to).len().max(start);
    s.get(start..end).unwrap_or("")
}

/// `word_rewrap`, `src/output.cpp:1558-1642`.
///
/// Walks the string one *decoded* character at a time, but copies raw bytes, so
/// the loop index is a byte offset and `lastwb`/`lastout` are byte offsets. A
/// break is allowed after `split` and on either side of a CJK or emoji
/// character; the reference avoids a break before a wide character by
/// preferring `old_j`, and always keeps at least one character per line.
#[must_use]
pub fn word_rewrap(input: &str, width: i32, split: char) -> String {
    let mut out = String::with_capacity(input.len());
    let tag_positions = get_tag_positions(input);
    let bytes = input.as_bytes();
    let mut lastwb: i32 = 0;
    let mut lastout: i32 = 0;
    let mut skipping_tag = false;
    let mut just_wrapped = false;
    let mut j: i32 = 0;
    let mut x: i32 = 0;
    let split_cp = u32::from(split as u8);
    while let Some(tail) = usize::try_from(j).ok().and_then(|start| bytes.get(start..)) {
        if tail.is_empty() {
            break;
        }
        let (decoded, used) = utf8_getch(tail);
        // Undecodable bytes become UNKNOWN_UNICODE, which `mk_wcwidth` reports
        // as one column -- unlike `utf8_width`, which skips them.
        let uc = decoded.unwrap_or(UNKNOWN_UNICODE);
        let at = usize::try_from(j).unwrap_or(usize::MAX);
        if uc == u32::from(b'<') && tag_positions.contains(&at) {
            skipping_tag = true;
        }
        let old_j = j;
        j += i32::try_from(used.max(1)).unwrap_or(1);
        if skipping_tag {
            if uc == u32::from(b'>') {
                skipping_tag = false;
            }
            continue;
        }
        if just_wrapped && uc == u32::from(b' ') {
            lastwb = j;
            lastout = j;
            continue;
        }
        x += mk_wcwidth(uc);
        if uc == split_cp || is_cjk_or_emoji(uc) {
            lastwb = if x <= width { j } else { old_j };
        }
        if x > width {
            if lastwb == lastout {
                lastwb = old_j;
            }
            if lastwb == lastout {
                lastwb = j;
            }
            let (from, to) = (
                usize::try_from(lastout).unwrap_or(0),
                usize::try_from(lastwb).unwrap_or(0),
            );
            out.push_str(byte_range(input, from, to));
            out.push('\n');
            x = 0;
            lastout = lastwb;
            j = lastwb;
            just_wrapped = true;
        } else {
            just_wrapped = false;
        }
    }
    let from = usize::try_from(lastout).unwrap_or(0);
    out.push_str(byte_range(input, from, input.len()));
    out
}

/// `std::getline(stream, line, '\n')` semantics: an empty stream yields no
/// line at all, and a trailing delimiter does not produce a final empty line.
fn getline(data: &str) -> Vec<&str> {
    if data.is_empty() {
        return Vec::new();
    }
    let mut parts: Vec<&str> = data.split('\n').collect();
    if data.ends_with('\n') {
        parts.pop();
    }
    parts
}

