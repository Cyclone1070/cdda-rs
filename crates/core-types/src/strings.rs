/// A plural-forms expression from a `.po` header, e.g.
/// `nplurals=2; plural=(n != 1);`.
///
/// The reference parses this expression with a dedicated evaluator
/// (`src/translation_plural_evaluator.cpp`, `src/translation_manager_impl.cpp`)
/// and evaluates it per count; the language rule is therefore *data*, not code.
/// The port reproduces the precedence table
/// (`TranslationPluralRulesEvaluator::OperatorPrecedence`) and the C semantics
/// of each operator: integer arithmetic, a non-zero test for `!`, and 0/1
/// results from comparisons and the logical operators.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PluralRule {
    /// `nplurals` from the header: the number of forms a plural entry must have.
    forms: usize,
    expression: Expr,
}

/// A node of the plural expression.
#[derive(Debug, Clone, PartialEq, Eq)]
enum Expr {
    /// The variable `n`.
    Count,
    /// An integer literal.
    Constant(i64),
    /// A unary or binary operator and its operands.
    Unary(UnaryOp, Box<Expr>),
    /// A binary operator and its operands.
    Binary(BinaryOp, Box<Expr>, Box<Expr>),
    /// `condition ? then : otherwise`.
    Conditional(Box<Expr>, Box<Expr>, Box<Expr>),
}

/// The unary operators the reference's lexer emits.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum UnaryOp {
    /// `!`
    Not,
}

/// The binary operators the reference's lexer emits.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum BinaryOp {
    /// `+`
    Plus,
    /// `-`
    Minus,
    /// `*`
    Times,
    /// `/`
    Divide,
    /// `%`
    Remainder,
    /// `<`
    Less,
    /// `==`
    Equal,
    /// `>`
    Greater,
    /// `<=`
    LessOrEqual,
    /// `>=`
    GreaterOrEqual,
    /// `!=`
    NotEqual,
    /// `&&`
    And,
    /// `||`
    Or,
}

/// A plural-forms expression the reference would reject.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PluralRuleError {
    /// What was wrong, in the evaluator's terms.
    pub reason: String,
}

impl PluralRuleError {
    fn new(reason: impl Into<String>) -> Self {
        Self {
            reason: reason.into(),
        }
    }
}

impl std::fmt::Display for PluralRuleError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "invalid plural forms header: {}", self.reason)
    }
}

/// The default gettext header rule, `nplurals=2; plural=(n != 1);`.
const DEFAULT_PLURAL_FORMS: &str = "nplurals=2; plural=(n != 1);";

impl PluralRule {
    /// The rule the reference uses when there is no header: singular for
    /// exactly `n == 1`.
    #[must_use]
    pub fn default_rule() -> Self {
        Self::parse(DEFAULT_PLURAL_FORMS).unwrap_or(Self {
            forms: 2,
            expression: Expr::Binary(
                BinaryOp::NotEqual,
                Box::new(Expr::Count),
                Box::new(Expr::Constant(1)),
            ),
        })
    }

    /// Parse a header fragment of the form `nplurals=<N>; plural=<expression>;`.
    ///
    /// # Errors
    ///
    /// Returns [`PluralRuleError`] when a key is missing, `nplurals` is not a
    /// positive integer, or the expression does not parse.
    ///
    /// Both keys are required and may appear in either order, which is what the
    /// reference's `TranslationManager` reads out of the `Plural-Forms` header.
    pub fn parse(header: &str) -> Result<Self, PluralRuleError> {
        let mut forms: Option<usize> = None;
        let mut expression: Option<&str> = None;
        for field in header.split(';') {
            let field = field.trim();
            if field.is_empty() {
                continue;
            }
            let Some((key, value)) = field.split_once('=') else {
                return Err(PluralRuleError::new(format!(
                    "expected key=value, found '{field}'"
                )));
            };
            match key.trim() {
                "nplurals" => {
                    let count = value.trim().parse::<usize>().map_err(|_| {
                        PluralRuleError::new(format!("nplurals is not a number: '{value}'"))
                    })?;
                    if count == 0 {
                        return Err(PluralRuleError::new("nplurals must be positive"));
                    }
                    forms = Some(count);
                }
                "plural" => expression = Some(value.trim()),
                other => {
                    return Err(PluralRuleError::new(format!("unknown key '{other}'")));
                }
            }
        }
        let forms = forms.ok_or_else(|| PluralRuleError::new("missing nplurals"))?;
        let source = expression.ok_or_else(|| PluralRuleError::new("missing plural"))?;
        let mut parser = ExprParser::new(source);
        let expression = parser.parse()?;
        Ok(Self { forms, expression })
    }

    /// The number of forms a plural entry must provide.
    #[must_use]
    pub fn form_count(&self) -> usize {
        self.forms
    }

    /// `TranslationPluralRulesEvaluator::Evaluate`: the form index for `n`.
    ///
    /// An index outside `0..nplurals` is an error in the reference, which the
    /// caller then turns into "use form 0" (`GetTranslatedStringPlural`).
    #[must_use]
    pub fn form_for(&self, n: u64) -> usize {
        let value = self.expression.evaluate(n);
        usize::try_from(value)
            .ok()
            .filter(|f| *f < self.forms)
            .unwrap_or(0)
    }
}

impl Expr {
    /// `ExprNode::Evaluate`, including its C integer semantics.
    fn evaluate(&self, n: u64) -> i64 {
        match self {
            Self::Count => i64::try_from(n).unwrap_or(i64::MAX),
            Self::Constant(value) => *value,
            Self::Unary(UnaryOp::Not, inner) => i64::from(inner.evaluate(n) == 0),
            Self::Binary(op, lhs, rhs) => {
                // The reference evaluates both operands before the operator, so
                // `&&` and `||` are not short-circuiting.
                let a = lhs.evaluate(n);
                let b = rhs.evaluate(n);
                match op {
                    BinaryOp::Plus => a.saturating_add(b),
                    BinaryOp::Minus => a.saturating_sub(b),
                    BinaryOp::Times => a.saturating_mul(b),
                    // Division and remainder by zero raise in the reference; a
                    // saturating 0 keeps the port total.
                    BinaryOp::Divide => a.checked_div(b).unwrap_or(0),
                    BinaryOp::Remainder => a.checked_rem(b).unwrap_or(0),
                    BinaryOp::Less => i64::from(a < b),
                    BinaryOp::Equal => i64::from(a == b),
                    BinaryOp::Greater => i64::from(a > b),
                    BinaryOp::LessOrEqual => i64::from(a <= b),
                    BinaryOp::GreaterOrEqual => i64::from(a >= b),
                    BinaryOp::NotEqual => i64::from(a != b),
                    BinaryOp::And => i64::from(a != 0 && b != 0),
                    BinaryOp::Or => i64::from(a != 0 || b != 0),
                }
            }
            Self::Conditional(condition, then, otherwise) => {
                if condition.evaluate(n) != 0 {
                    then.evaluate(n)
                } else {
                    otherwise.evaluate(n)
                }
            }
        }
    }
}

/// `OperatorPrecedence`, `src/translation_plural_evaluator.cpp`: higher binds
/// tighter. `?:` is the loosest and right-associative.
fn operator_precedence(op: Op) -> u8 {
    match op {
        Op::Question => 0,
        Op::Or => 1,
        Op::And => 2,
        Op::Equal | Op::NotEqual => 3,
        Op::Less | Op::Greater | Op::LessOrEqual | Op::GreaterOrEqual => 4,
        Op::Plus | Op::Minus => 5,
        Op::Times | Op::Divide | Op::Remainder => 6,
    }
}

/// A binary operator as the lexer sees it, before it becomes an [`Expr`].
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Op {
    Plus,
    Minus,
    Times,
    Divide,
    Remainder,
    Less,
    Equal,
    Greater,
    LessOrEqual,
    GreaterOrEqual,
    NotEqual,
    And,
    Or,
    Question,
}

impl Op {
    fn to_binary(self) -> Option<BinaryOp> {
        Some(match self {
            Op::Plus => BinaryOp::Plus,
            Op::Minus => BinaryOp::Minus,
            Op::Times => BinaryOp::Times,
            Op::Divide => BinaryOp::Divide,
            Op::Remainder => BinaryOp::Remainder,
            Op::Less => BinaryOp::Less,
            Op::Equal => BinaryOp::Equal,
            Op::Greater => BinaryOp::Greater,
            Op::LessOrEqual => BinaryOp::LessOrEqual,
            Op::GreaterOrEqual => BinaryOp::GreaterOrEqual,
            Op::NotEqual => BinaryOp::NotEqual,
            Op::And => BinaryOp::And,
            Op::Or => BinaryOp::Or,
            Op::Question => return None,
        })
    }
}

/// A lexed token of a plural expression.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Token {
    Count,
    Constant(i64),
    Op(Op),
    Not,
    Open,
    Close,
    Colon,
}

/// A precedence-climbing parser for the gettext plural expression grammar.
struct ExprParser<'a> {
    source: &'a str,
    bytes: usize,
}

impl<'a> ExprParser<'a> {
    fn new(source: &'a str) -> Self {
        Self { source, bytes: 0 }
    }

    fn parse(&mut self) -> Result<Expr, PluralRuleError> {
        let expr = self.parse_binary(0)?;
        self.skip_space();
        if self.bytes < self.source.len() {
            return Err(PluralRuleError::new(format!(
                "trailing input at byte {}",
                self.bytes
            )));
        }
        Ok(expr)
    }

    fn skip_space(&mut self) {
        while let Some(c) = self.source.get(self.bytes..).and_then(|s| s.chars().next()) {
            if !c.is_whitespace() {
                break;
            }
            self.bytes += c.len_utf8();
        }
    }

    fn next_token(&mut self) -> Result<Option<Token>, PluralRuleError> {
        self.skip_space();
        let rest = self.source.get(self.bytes..).unwrap_or("");
        let Some(c) = rest.chars().next() else {
            return Ok(None);
        };
        let two = |a: char, b: char| rest.starts_with([a, b].iter().collect::<String>().as_str());
        let token = match c {
            'n' if !rest.starts_with("nplurals") => Token::Count,
            '!' if two('!', '=') => Token::Op(Op::NotEqual),
            '!' => Token::Not,
            '=' if two('=', '=') => Token::Op(Op::Equal),
            '<' if two('<', '=') => Token::Op(Op::LessOrEqual),
            '<' => Token::Op(Op::Less),
            '>' if two('>', '=') => Token::Op(Op::GreaterOrEqual),
            '>' => Token::Op(Op::Greater),
            '+' => Token::Op(Op::Plus),
            '-' => Token::Op(Op::Minus),
            '*' => Token::Op(Op::Times),
            '/' => Token::Op(Op::Divide),
            '%' => Token::Op(Op::Remainder),
            '&' if two('&', '&') => Token::Op(Op::And),
            '|' if two('|', '|') => Token::Op(Op::Or),
            '?' => Token::Op(Op::Question),
            '(' => Token::Open,
            ')' => Token::Close,
            ':' => Token::Colon,
            c if c.is_ascii_digit() => {
                let digits: String = rest.chars().take_while(char::is_ascii_digit).collect();
                self.bytes += digits.len();
                let value = digits.parse::<i64>().map_err(|_| {
                    PluralRuleError::new(format!("integer out of range: '{digits}'"))
                })?;
                return Ok(Some(Token::Constant(value)));
            }
            other => {
                return Err(PluralRuleError::new(format!(
                    "unexpected character '{other}' in plural expression"
                )));
            }
        };
        self.bytes += if matches!(
            token,
            Token::Op(
                Op::NotEqual | Op::Equal | Op::LessOrEqual | Op::GreaterOrEqual | Op::And | Op::Or
            )
        ) {
            2
        } else {
            c.len_utf8()
        };
        Ok(Some(token))
    }

    fn parse_binary(&mut self, min_precedence: u8) -> Result<Expr, PluralRuleError> {
        let mut lhs = self.parse_unary()?;
        loop {
            let checkpoint = self.bytes;
            let Some(token) = self.next_token()? else {
                return Ok(lhs);
            };
            let Token::Op(op) = token else {
                self.bytes = checkpoint;
                return Ok(lhs);
            };
            let precedence = operator_precedence(op);
            if precedence < min_precedence {
                self.bytes = checkpoint;
                return Ok(lhs);
            }
            if op == Op::Question {
                // `cond ? then : else`, the then-branch parsed one level tighter
                // so a nested `?:` still binds right-associatively.
                let then = self.parse_binary(precedence + 1)?;
                let Some(Token::Colon) = self.next_token()? else {
                    return Err(PluralRuleError::new("expected ':' after '?'"));
                };
                let otherwise = self.parse_binary(precedence)?;
                lhs = Expr::Conditional(Box::new(lhs), Box::new(then), Box::new(otherwise));
                continue;
            }
            let Some(binary) = op.to_binary() else {
                return Err(PluralRuleError::new("operator is not binary"));
            };
            let rhs = self.parse_binary(precedence + 1)?;
            lhs = Expr::Binary(binary, Box::new(lhs), Box::new(rhs));
        }
    }

    fn parse_unary(&mut self) -> Result<Expr, PluralRuleError> {
        let checkpoint = self.bytes;
        match self.next_token()? {
            Some(Token::Not) => {
                let inner = self.parse_unary()?;
                Ok(Expr::Unary(UnaryOp::Not, Box::new(inner)))
            }
            Some(Token::Count) => Ok(Expr::Count),
            Some(Token::Constant(value)) => Ok(Expr::Constant(value)),
            Some(Token::Open) => {
                let inner = self.parse_binary(0)?;
                let Some(Token::Close) = self.next_token()? else {
                    return Err(PluralRuleError::new("expected ')'"));
                };
                Ok(inner)
            }
            _ => {
                self.bytes = checkpoint;
                Err(PluralRuleError::new("expected a value"))
            }
        }
    }
}

/// A loaded translation catalogue for one language.
///
/// The reference keeps this in the process-wide `TranslationManager` singleton
/// (`translation_manager.h`) and the `_` macro caches call sites against it; the
/// port makes it an ordinary value so a test, a tool or a second language can
/// hold one without touching global state.
#[derive(Debug, Clone)]
pub struct Catalogue {
    entries: BTreeMap<String, Entry>,
    rule: PluralRule,
}

impl Default for Catalogue {
    fn default() -> Self {
        Self {
            entries: BTreeMap::new(),
            rule: PluralRule::default_rule(),
        }
    }
}

impl Catalogue {
    /// An empty catalogue for a language with the given `plural=` rule.
    ///
    /// # Panics
    ///
    /// Never: an unparseable header falls back to the default rule. Use
    /// [`Catalogue::try_with_plural_forms`] to see the error.
    #[must_use]
    pub fn with_plural_forms(header: &str) -> Self {
        Self {
            entries: BTreeMap::new(),
            rule: PluralRule::parse(header).unwrap_or_else(|_| PluralRule::default_rule()),
        }
    }

    /// An empty catalogue, failing on a malformed header.
    ///
    /// # Errors
    ///
    /// Returns [`PluralRuleError`] when the header does not parse.
    pub fn try_with_plural_forms(header: &str) -> Result<Self, PluralRuleError> {
        Ok(Self {
            entries: BTreeMap::new(),
            rule: PluralRule::parse(header)?,
        })
    }

    /// The plural rule this catalogue was loaded with.
    #[must_use]
    pub fn plural_rule(&self) -> &PluralRule {
        &self.rule
    }

    /// Add one entry: a msgid (or a [`contextual_key`]) and its translated
    /// forms. A plural entry supplies one string per form.
    pub fn insert(&mut self, key: &str, forms: &[&str]) {
        self.entries.insert(
            key.to_owned(),
            Entry {
                forms: forms.iter().map(|s| (*s).to_owned()).collect(),
            },
        );
    }

    /// Number of entries.
    #[must_use]
    pub fn len(&self) -> usize {
        self.entries.len()
    }

    /// Whether the catalogue has no entries.
    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.entries.is_empty()
    }

    /// The translated forms for `key`, if present.
    fn lookup(&self, key: &str) -> Option<&str> {
        self.entries
            .get(key)
            .and_then(|entry| entry.forms.first())
            .map(String::as_str)
    }

    /// `GetTranslatedStringPlural`: the form selected by the catalogue's rule,
    /// falling back to form 0 when the rule picks a form the entry does not
    /// have (the reference logs "Plural forms expression evaluated out-of-bound"
    /// and returns the first form).
    fn lookup_plural(&self, key: &str, n: u64) -> Option<&str> {
        let entry = self.entries.get(key)?;
        let index = self.rule.form_for(n);
        entry
            .forms
            .get(index)
            .or_else(|| entry.forms.first())
            .map(String::as_str)
    }
}

/// `n_gettext( singular, plural, n )` with the catalogue passed in.
///
/// Reference: `TranslatePlural`, `src/translation_manager_impl.cpp:178-192`.
///
/// A hit selects a form with the catalogue's plural rule; a miss takes the
/// reference's fallback, which compares `n` to 1 exactly and ignores the
/// language's rule entirely (that asymmetry is the reference's, not the port's).
#[must_use]
pub fn n_gettext<'a>(
    catalogue: Option<&'a Catalogue>,
    singular: &'a str,
    plural: &'a str,
    n: u64,
) -> &'a str {
    match catalogue.and_then(|c| c.lookup_plural(singular, n)) {
        Some(form) => form,
        None => {
            if n == 1 {
                singular
            } else {
                plural
            }
        }
    }
}

/// `npgettext( context, singular, plural, n )` with the catalogue passed in.
///
/// Reference: `TranslatePluralWithContext`,
/// `src/translation_manager_impl.cpp:218-242`.
#[must_use]
pub fn npgettext<'a>(
    catalogue: Option<&'a Catalogue>,
    context: &str,
    singular: &'a str,
    plural: &'a str,
    n: u64,
) -> &'a str {
    let key = contextual_key(context, singular);
    match catalogue.and_then(|c| c.lookup_plural(&key, n)) {
        Some(form) => form,
        None => {
            if n == 1 {
                singular
            } else {
                plural
            }
        }
    }
}
