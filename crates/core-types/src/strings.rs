/// `u32_to_lowercase`, `src/unicode.cpp:75-96`.
///
/// A hand-written approximation of lower-casing, kept verbatim. Two of its
/// ranges are wider than the alphabets they mean to cover:
///
/// * `0xC0..=0xDE` shifts by `0x20`, which sweeps up U+00D7 `×` and turns it
///   into U+00F7 `÷`;
/// * `0x100..=0x137` and friends lower-case by "even code point + 1", which maps
///   U+0130 `İ` to U+0131 `ı`.
///
/// Everything outside the table (Greek, CJK, ...) is returned unchanged.
#[must_use]
pub fn to_lowercase_char(ch: char) -> char {
    let cp = u32::from(ch);
    let mapped = if (0x41..=0x5A).contains(&cp)
        || (0xC0..=0xDE).contains(&cp)
        || (0x410..=0x42F).contains(&cp)
    {
        cp + 0x20
    } else if (0x401..=0x40F).contains(&cp) {
        cp + 0x50
    } else if cp == 0x178 {
        0xFF
    } else if (0x100..=0x137).contains(&cp)
        || (0x14A..=0x177).contains(&cp)
        || (0x460..=0x481).contains(&cp)
        || (0x490..=0x4BF).contains(&cp)
        || (0x4D0..=0x52F).contains(&cp)
    {
        if cp % 2 == 0 { cp + 1 } else { cp }
    } else if (0x139..=0x148).contains(&cp)
        || (0x179..=0x17E).contains(&cp)
        || (0x4C1..=0x4CC).contains(&cp)
    {
        if cp % 2 == 1 { cp + 1 } else { cp }
    } else {
        cp
    };
    char::from_u32(mapped).unwrap_or(ch)
}

/// The C-locale `towupper` of one character: ASCII only.
fn c_locale_towupper(ch: char) -> char {
    if ch.is_ascii_lowercase() {
        ch.to_ascii_uppercase()
    } else {
        ch
    }
}

/// The C-locale `towlower` of one character: ASCII only.
fn c_locale_towlower(ch: char) -> char {
    if ch.is_ascii_uppercase() {
        ch.to_ascii_lowercase()
    } else {
        ch
    }
}

