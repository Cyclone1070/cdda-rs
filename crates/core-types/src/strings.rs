/// `foldstring`, `src/output.cpp:127-184`.
///
/// Wraps each input line with [`word_rewrap`], then re-opens the colour tags
/// that were still active at the end of the previous output line and re-closes
/// them, so every returned line is independently colourable. A `width < 1`
/// disables wrapping entirely.
#[must_use]
pub fn foldstring_with_split(s: &str, width: i32, split: char) -> Vec<String> {
    let mut lines = Vec::new();
    let mut open_tags: Vec<String> = Vec::new();
    for line in getline(s) {
        if line.is_empty() {
            lines.push(String::new());
            continue;
        }
        let wrapped = if width >= 1 {
            word_rewrap(line, width, split)
        } else {
            line.to_owned()
        };
        for raw_line in getline(&wrapped) {
            // Re-open the tags closed in the previous line.
            let mut current = String::new();
            for tag in &open_tags {
                current.push_str(tag);
            }
            current.push_str(raw_line);
            // Track the tags this line opens and closes.
            for position in get_tag_positions(raw_line) {
                let is_closing = raw_line
                    .as_bytes()
                    .get(position + 1)
                    .is_some_and(|&b| b == b'/');
                if is_closing {
                    open_tags.pop();
                } else if let Some(offset) =
                    raw_line.get(position..).and_then(|tail| tail.find('>'))
                {
                    open_tags.push(
                        byte_prefix(raw_line.get(position..).unwrap_or(""), offset + 1).to_owned(),
                    );
                }
            }
            // Close whatever is still open at the end of this line.
            for _ in 0..open_tags.len() {
                current.push_str("</color>");
            }
            lines.push(current);
        }
    }
    lines
}

